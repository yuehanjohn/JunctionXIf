export type Mover = {
  id: string;
  name: string;
  tagline: string;
  city: string;
  rating: number;
  reviews: number;
  /** % of moves that end in a damage claim — our trust metric. */
  damageRate: number;
  onTimeRate: number;
  crew: number;
  vans: number;
  /** Moves this operator can run per day — feeds the sold-out slot model. */
  dailyCapacity: number;
  services: MoverService[];
  pros: string[];
  cons: string[];
  /** € per mover-hour, labour only. */
  hourlyRate: number;
  minHours: number;
  /** € per km for the van leg. */
  mileagePerKm: number;
  /** Labour multiplier for Fri–Sun. */
  weekendFactor: number;
  /** € flat handling fee when the moving-day score is risky (ice/snow). */
  weatherRiskFee: number;
  /** True when the price is locked at booking, not "estimated". */
  priceLock: boolean;
  /** Operator's included damage cover in € — comparison data, never a substitute for home insurance. */
  insuranceCap: number;
  instantBooking: boolean;
};

